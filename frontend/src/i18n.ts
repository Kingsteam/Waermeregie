export type Lang = "de" | "en";

export function translate(lang: Lang, key: I18nKey, vars?: Record<string, string | number>): string {
  let s: string = (lang === "en" ? en[key] : undefined) ?? de[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  }
  return s;
}

export type T = (key: I18nKey, vars?: Record<string, string | number>) => string;

export function translator(lang: Lang): T {
  return (key, vars) => translate(lang, key, vars);
}
